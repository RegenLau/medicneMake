function articleSections(topic, layout) {
  if (layout === "临床深度版") {
    const caseText = topic.consultationInCase ? `${topic.caseText}\n\n${topic.reminder}` : topic.caseText;
    return [
      ...topic.points.map(({ clinicalHeading, why, check }) => [clinicalHeading, `${why}\n\n${check}`]),
      [topic.caseHeading, caseText, topic.caseVisual],
      ...(topic.consultationInCase ? [] : [["核对与咨询", topic.reminder]]),
    ];
  }
  if (layout === "避坑问答版") {
    return [
      ...topic.points.map(({ question, answer, visual, illustrateAnswer }) => [question, answer, illustrateAnswer ? visual : null]),
      ...topic.moreQuestions,
    ];
  }
  return [
    ...topic.points.map(({ heading, steps, visual }) => [heading, steps, visual]),
    ...(topic.guideCase ? [topic.guideCase] : []),
    ["药师提醒", topic.reminder],
  ];
}

function planArticle(w) {
  const title = w.topic.trim();
  const topic = articleTopics[title];
  const lead = { "临床深度版": topic.background, "避坑问答版": topic.qaLead }[w.layout] || topic.lead;
  return { title, lead, blocks: articleBlocks(articleSections(topic, w.layout)) };
}

function articleBlocks(sections) {
  return sections.map(([name, line, visual]) => ({
    name, line, image: "", seconds: 0, variant: 0,
    ...(visual ? { suggestedImage: true } : {}),
    prompt: visual || "",
  }));
}
