const allVideoTopics = Object.keys(videoTopics);

function planVideo(w, maxSeconds) {  const title = w.topic.trim();
  const beats = videoTopics[title]
    .map(([name, line, scene, priority = 0], index) => ({
      name, line, scene, priority, index,
      seconds: Math.min(maxSeconds, recommendedShotSeconds(spokenChars(line))),
    }));
  const reference = videoReferenceSeconds(w);
  const shots = beats.filter(({ priority }) => !priority);
  let seconds = shots.reduce((sum, shot) => sum + shot.seconds, 0);
  const extras = beats.filter(({ priority }) => priority).sort((a, b) => a.priority - b.priority);
  for (const shot of extras) {
    if (shots.length === maxVideoShots) break;
    if (reference === null || seconds + shot.seconds > reference) continue;
    shots.push(shot);
    seconds += shot.seconds;
  }
  shots.sort((a, b) => a.index - b.index);
  return { title, setting: videoTopicSettings[title] || "", blocks: videoBlocks(shots) };
}

function videoBlocks(shots) {
  return shots.map(({ name, line, scene, seconds, motion }) => ({
    name: name.slice(0, 60), line, image: "", variant: 0, seconds,
    prompt: scene,
    motion: motion || defaultMotion,
  }));
}
